<?php

namespace Symphograph\Bicycle\Repo\Redis;

/**
 * Модификаторы для установки времени жизни ключа в Redis.
 *
 * @see https://redis.io/commands/expire
 */
enum TTLMode: string
{
    /**
     * Установить время жизни только если у ключа его нет.
     */
    case NX = 'NX';

    /**
     * Установить время жизни только если у ключа уже есть TTL.
     */
    case XX = 'XX';

    /**
     * Установить время жизни только если новое значение меньше текущего.
     */
    case LT = 'LT';

    /**
     * Установить время жизни только если новое значение больше текущего.
     */
    case GT = 'GT';
}
